(async () => {
  const results = [];
  const assert = (name, pass) => results.push({ name, pass: Boolean(pass) });
  const hidden = node => getComputedStyle(node).display === 'none';
  const button = label => document.querySelector(`button[data-navbar-item][aria-label="${label}"]`);
  const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
  const set = value => chrome.storage.local.set({ whatsappFocus: value });
  // Detect accidental reads of chat content through the control scanner.
  Object.defineProperty(document.getElementById('private-message'), 'textContent', { get() { throw new Error('Message text was read'); } });
  await wait(220);
  for (const label of ['Channels', 'Communities', 'Meta AI', 'Media']) assert(`${label} hidden with its wrapper`, hidden(button(label)) && hidden(button(label).parentElement));
  assert('Existing Status preference preserved', !hidden(button('Status')));
  assert('Calls and Chats preserved', !hidden(button('Calls')) && !hidden(button('Chats')));
  assert('Archived with counter hidden', hidden(document.querySelector('[aria-label="Archived, 3 unread messages"]')));
  let currentArchive = document.querySelector('button[data-testid="chatlist-panel-archived-button"]');
  assert('Current Archived button with trailing space and unread badge is hidden', hidden(currentArchive));
  assert('Archive action on a conversation stays visible', !hidden(document.getElementById('archive-action')));
  assert('Locked Chats hidden', hidden(document.querySelector('[aria-label="Locked chats"]')));
  assert('Ask Meta AI hidden', hidden(document.getElementById('ai')));
  assert('Message and conversation controls preserved', !hidden(document.getElementById('private-message')) && !hidden(document.getElementById('chat-button')));
  assert('Old group visibility markers removed', !document.documentElement.classList.contains('waf-groups') && !document.querySelector('[data-waf-group]') && !document.getElementById('waf-group-progress'));
  assert('Group row stays visible', getComputedStyle(document.querySelector('[role="row"]')).visibility === 'visible');
  const migrated = (await chrome.storage.local.get('whatsappFocus')).whatsappFocus;
  assert('Obsolete group setting removed without resetting Status', !Object.hasOwn(migrated, 'groups') && migrated.status === false);
  assert('Obsolete metadata removed', !(await chrome.storage.local.get('whatsappFocusGroupStatus')).whatsappFocusGroupStatus && !(await chrome.storage.local.get('whatsappFocusGroupScan')).whatsappFocusGroupScan);
  const international = document.createElement('div');
  const internationalButton = document.createElement('button');
  internationalButton.setAttribute('data-navbar-item', 'true'); internationalButton.setAttribute('aria-label', '地域別の名前');
  internationalButton.innerHTML = '<svg><title>wds-ic-channels</title></svg>';
  international.append(internationalButton); document.getElementById('new-ui').append(international);
  await wait(150);
  assert('Language-independent icon detects dynamically inserted Channels', hidden(internationalButton) && hidden(international));
  const replacement = currentArchive.cloneNode(true);
  replacement.setAttribute('aria-label', 'Arquivadas ');
  currentArchive.replaceWith(replacement);
  currentArchive = replacement;
  assert('Recreated Archived button in another language stays hidden', hidden(currentArchive));
  await set({ ...migrated, enabled: false });
  assert('Master pause restores the current Archived button', !hidden(currentArchive));
  assert('Master pause restores navigation and standalone controls', ['Status','Channels','Communities','Meta AI','Media'].every(label => !hidden(button(label))) && !hidden(document.querySelector('[aria-label="Locked chats"]')) && !hidden(document.getElementById('ai')));
  await set({ ...migrated, enabled: true, archived: false, lockedChats: false, metaAI: false });
  assert('Turning off only Archived restores the current button', !hidden(currentArchive) && hidden(button('Channels')));
  assert('Individual controls restore only the selected features', !hidden(document.querySelector('[aria-label="Locked chats"]')) && !hidden(document.getElementById('ai')) && hidden(button('Channels')));
  await set(migrated);
  assert('Re-enabling Archived hides the button again', hidden(currentArchive));
  const profile = document.getElementById('profile-ring');
  const decoration = document.getElementById('status-decoration');
  const ring = decoration.querySelector('circle');
  const avatar = document.getElementById('status-avatar');
  const avatarImage = avatar.querySelector('image');
  const avatarMask = avatar.querySelector('mask circle');
  const avatarOutline = avatar.querySelector('g[stroke] circle');
  const plainAvatar = document.getElementById('plain-avatar');
  const diameter = plainAvatar.getBoundingClientRect().width;
  const fitsAvatar = (node, width, inset) => {
    const { x, y, width: boxWidth, height } = node.getBBox();
    return x === inset && y === inset && boxWidth === width && height === width;
  };
  const border = () => getComputedStyle(profile).borderTopColor;
  const stroke = () => getComputedStyle(ring).stroke;
  const originalBorder = border();
  const originalStroke = stroke();
  assert('Status off leaves the status decorations visible', originalBorder === 'rgb(46, 139, 87)' && originalStroke === 'rgb(46, 139, 87)');
  const originalSize = () => [avatarImage, avatarMask, avatarOutline].every(node => fitsAvatar(node, diameter - 8, 4));
  assert('The native status layout reserves four pixels around the photo', originalSize());
  await set({ ...migrated, status: true });
  assert('Status on hides the ring in the current chat list', border() === 'rgba(0, 0, 0, 0)' && stroke() === 'none');
  assert('Avatar, chat control and unread count stay visible', ['profile-ring', 'status-avatar', 'status-chat', 'unread-badge'].every(id => !hidden(document.getElementById(id))));
  assert('Avatar image, mask and native photo outline stay visible', !hidden(avatarImage) && !hidden(avatarMask) && getComputedStyle(avatarOutline).stroke === 'rgb(138, 155, 177)');
  assert('The photo and mask fill the same space as a regular avatar', fitsAvatar(avatarImage, diameter, 0) && fitsAvatar(avatarMask, diameter, 0));
  assert('The outline moves to the edge without being clipped', fitsAvatar(avatarOutline, diameter - 1, 0.5));
  const inserted = decoration.cloneNode(true);
  inserted.removeAttribute('id');
  inserted.setAttribute('data-testid', 'status-ring');
  profile.after(inserted);
  assert('A newly rendered standalone SVG ring is also hidden', hidden(inserted));
  const otherRing = inserted.cloneNode(true);
  document.getElementById('new-ui').append(otherRing);
  assert('A generic ring outside the chat list is unaffected', !hidden(otherRing));
  await set({ ...migrated, enabled: false, status: true });
  assert('Master pause restores ring decorations', border() === originalBorder && stroke() === originalStroke && !hidden(inserted));
  await set(migrated);
  assert('Turning off only Status restores both types of ring', border() === originalBorder && stroke() === originalStroke && !hidden(inserted) && hidden(button('Channels')));
  assert('Turning off Status restores the original photo inset', originalSize());
  const favicon = document.getElementById('tab-icon');
  const originalIcon = favicon.getAttribute('href');
  document.title = '(3) WhatsApp (Web)';
  assert('The unread title is unchanged while the tab option is off', document.title === '(3) WhatsApp (Web)');
  assert('Fixed tab icon starts off for existing installs', !migrated.favicon && originalIcon.endsWith('icon16.png'));
  await set({ ...migrated, favicon: true });
  const pinnedIcon = favicon.getAttribute('href');
  assert('Enabling the option shows a bundled static icon', pinnedIcon.startsWith('data:image/png;base64,'));
  assert('The same option removes the leading unread count and keeps the rest of the title', document.title === 'WhatsApp (Web)');
  document.title = '(٩٩+) WhatsApp';
  await wait(30);
  assert('New counts with localized digits and a plus sign are removed', document.title === 'WhatsApp');
  const nextIcon = '../extension/icons/icon48.png';
  favicon.setAttribute('href', nextIcon);
  const alternateIcon = document.createElement('link');
  alternateIcon.rel = 'icon';
  alternateIcon.setAttribute('href', originalIcon);
  document.head.append(alternateIcon);
  await wait(30);
  assert('Changes to the counter and new favicon declarations are replaced', [favicon, alternateIcon].every(link => link.getAttribute('href') === pinnedIcon));
  await set({ ...migrated, favicon: true, enabled: false });
  assert('Pausing distractions restores the latest favicon from the site', favicon.getAttribute('href') === nextIcon && alternateIcon.getAttribute('href') === originalIcon);
  assert('Pausing restores the most recent unread count in the title', document.title === '(٩٩+) WhatsApp');
  await set({ ...migrated, favicon: true });
  document.title = 'WhatsApp';
  await wait(30);
  await set(migrated);
  assert('A native reset to zero stays clear when the option is disabled', document.title === 'WhatsApp');
  await set({ ...migrated, favicon: true });
  const replacementTitle = document.createElement('title');
  replacementTitle.textContent = '(7) WhatsApp';
  document.head.querySelector('title').replaceWith(replacementTitle);
  alternateIcon.remove();
  await wait(30);
  assert('New title nodes are handled', document.title === 'WhatsApp');
  assert('A removed favicon is released before it can be reused elsewhere', alternateIcon.getAttribute('href') === originalIcon);
  await set(migrated);
  assert('Turning off only the icon option restores the site favicon', favicon.getAttribute('href') === nextIcon && hidden(button('Channels')));
  assert('Turning off the option restores the replacement title intact', document.title === '(7) WhatsApp');
  const fail = results.filter(item => !item.pass);
  document.getElementById('result').textContent = `${results.length-fail.length}/${results.length} content checks passed`;
  for (const result of results) { const li=document.createElement('li'); li.textContent=`${result.pass?'OK':'FAIL'}: ${result.name}`; document.getElementById('checks').append(li); }
  document.body.dataset.result = fail.length ? 'fail' : 'pass';
})();
